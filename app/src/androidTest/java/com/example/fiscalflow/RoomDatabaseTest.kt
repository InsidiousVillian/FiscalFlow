package com.example.fiscalflow

import android.content.Context
import androidx.room.Room
import androidx.room.withTransaction
import androidx.test.core.app.ApplicationProvider
import androidx.test.ext.junit.runners.AndroidJUnit4
import com.example.fiscalflow.data.AppDatabase
import com.example.fiscalflow.data.BudgetGoalDao
import com.example.fiscalflow.data.CategoryDao
import com.example.fiscalflow.data.ExpenseDao
import com.example.fiscalflow.data.UserDao
import com.example.fiscalflow.data.UserProgressDao
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith

@RunWith(AndroidJUnit4::class)
class RoomDatabaseTest {

    private lateinit var db: AppDatabase
    private lateinit var userDao: UserDao
    private lateinit var categoryDao: CategoryDao
    private lateinit var expenseDao: ExpenseDao
    private lateinit var budgetGoalDao: BudgetGoalDao
    private lateinit var userProgressDao: UserProgressDao

    @Before
    fun setUp() {
        val context = ApplicationProvider.getApplicationContext<Context>()
        db = Room.inMemoryDatabaseBuilder(context, AppDatabase::class.java)
            .allowMainThreadQueries()
            .build()

        userDao = db.userDao()
        categoryDao = db.categoryDao()
        expenseDao = db.expenseDao()
        budgetGoalDao = db.budgetGoalDao()
        userProgressDao = db.userProgressDao()
    }

    @After
    fun tearDown() {
        db.close()
    }

    @Test
    fun userDao_insertAndFindByUsername_returnsInsertedUser() = runBlocking {
        val user = UserEntity(username = "alice", password = "secret")
        userDao.insert(user)

        val loaded = userDao.findByUsername("alice")
        assertNotNull("expected to find the user we just inserted", loaded)
        assertEquals("alice", loaded!!.username)
        assertEquals("secret", loaded.password)

        assertNull(userDao.findByUsername("does-not-exist"))
    }

    @Test
    fun categoryDao_insertDuplicate_isIgnoredByPrimaryKey() = runBlocking {
        val firstRowId = categoryDao.insert(CategoryEntity("Groceries", ownerUsername = "unassigned_legacy"))
        val secondRowId = categoryDao.insert(CategoryEntity("Groceries", ownerUsername = "unassigned_legacy"))

        assertTrue("first insert should succeed with a positive rowId", firstRowId > 0)
        assertEquals("duplicate insert should be ignored (rowId == -1L)", -1L, secondRowId)
        assertEquals(1, categoryDao.count("unassigned_legacy"))
    }

    @Test
    fun categoryDao_observeAll_emitsSortedCategories() = runBlocking {
        categoryDao.insert(CategoryEntity("utilities", ownerUsername = "unassigned_legacy"))
        categoryDao.insert(CategoryEntity("Groceries", ownerUsername = "unassigned_legacy"))
        categoryDao.insert(CategoryEntity("Rent", ownerUsername = "unassigned_legacy"))

        val emitted = categoryDao.observeAll("unassigned_legacy").first().map { it.name }
        assertEquals(listOf("Groceries", "Rent", "utilities"), emitted)
    }

    @Test
    fun expenseDao_insertAndObserveAll_returnsExpense() = runBlocking {
        val expense = Expense(
            amount = 12.50,
            startDate = "5/9/2026",
            endDate = "5/9/2026",
            description = "coffee",
            category = "Groceries",
            photoUri = null,
            ownerUsername = "unassigned_legacy"
        )
        val newId = expenseDao.insert(expense)
        assertTrue("autoGenerated id should be positive", newId > 0)

        val all = expenseDao.observeAll("unassigned_legacy").first()
        assertEquals(1, all.size)
        assertEquals(12.50, all[0].amount, 0.0001)
        assertEquals("coffee", all[0].description)
    }

    @Test
    fun budgetGoalDao_upsertReplacesPreviousRow() = runBlocking {
        budgetGoalDao.upsert(BudgetingGoal(minimum = 100.0, maximum = 500.0, month = 9, year = 2026, ownerUsername = "unassigned_legacy"))
        budgetGoalDao.upsert(BudgetingGoal(minimum = 200.0, maximum = 800.0, month = 10, year = 2026, ownerUsername = "unassigned_legacy"))

        val current = budgetGoalDao.observeCurrent("unassigned_legacy").first()
        assertNotNull(current)
        assertEquals(200.0, current!!.minimum, 0.0001)
        assertEquals(800.0, current.maximum, 0.0001)
        assertEquals(10, current.month)
    }

    @Test
    fun userProgressDao_upsertPersistsMilestonesString() = runBlocking {
        val progress = UsersProgress.fromList(
            xp = 42,
            streak = 3,
            milestones = listOf("first_expense", "first_goal", "week_streak"),
            ownerUsername = "unassigned_legacy"
        )
        userProgressDao.upsert(progress)

        val loaded = userProgressDao.observeCurrent("unassigned_legacy").first()
        assertNotNull(loaded)
        assertEquals(42, loaded!!.xp)
        assertEquals(3, loaded.streak)
        assertEquals("first_expense|first_goal|week_streak", loaded.milestonesRaw)
        assertEquals(
            listOf("first_expense", "first_goal", "week_streak"),
            loaded.milestones
        )
    }

    // Comprehensive Two-User Isolation Test: Proves User A cannot see User B's transactions or categories.
    @Test
    fun twoUser_isolation_userACannotSeeUserBData() = runBlocking {
        val expenseA = Expense(amount = 100.0, startDate = "1/1/2026", endDate = "1/1/2026", description = "UserA Expense", category = "Rent", ownerUsername = "UserA")
        val expenseB = Expense(amount = 200.0, startDate = "1/1/2026", endDate = "1/1/2026", description = "UserB Expense", category = "Groceries", ownerUsername = "UserB")

        expenseDao.insert(expenseA)
        expenseDao.insert(expenseB)

        val userAExpenses = expenseDao.observeAll("UserA").first()
        val userBExpenses = expenseDao.observeAll("UserB").first()

        assertEquals(1, userAExpenses.size)
        assertEquals("UserA Expense", userAExpenses[0].description)

        assertEquals(1, userBExpenses.size)
        assertEquals("UserB Expense", userBExpenses[0].description)

        categoryDao.insert(CategoryEntity("Travel", ownerUsername = "UserA"))
        categoryDao.insert(CategoryEntity("Movies", ownerUsername = "UserB"))

        assertEquals(1, categoryDao.observeAll("UserA").first().size)
        assertEquals("Travel", categoryDao.observeAll("UserA").first()[0].name)

        assertEquals(1, categoryDao.observeAll("UserB").first().size)
        assertEquals("Movies", categoryDao.observeAll("UserB").first()[0].name)
    }

    @Test
    fun database_withTransaction_rollsBackOnException() = runBlocking {
        val category = CategoryEntity("Travel", ownerUsername = "alice")
        try {
            db.withTransaction {
                categoryDao.insert(category)
                throw RuntimeException("Simulated failure during restore transaction")
            }
        } catch (e: RuntimeException) {
            assertEquals("Simulated failure during restore transaction", e.message)
        }

        assertEquals(0, categoryDao.count("alice"))
    }

    @Test
    fun productionAppDatabase_createsFiscalFlowDbFile() = runBlocking {
        val context = ApplicationProvider.getApplicationContext<Context>()
        val real = AppDatabase.get(context)
        real.userDao().count()

        val dbFile = context.getDatabasePath("fiscalflow.db")
        assertTrue(
            "expected fiscalflow.db to exist at ${dbFile.absolutePath}",
            dbFile.exists()
        )
    }
}
